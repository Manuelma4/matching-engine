#!/usr/bin/env python3
"""Run nine fictional one-U queue examples using only the Python standard library.

No files are read or written by the example logic. The seed is hand supplied,
alongside five generated wire frames; its digest is a reproducible identifier,
not external source authentication. All times are fictional nanoseconds.
"""
import sys

sys.dont_write_bytecode = True

import argparse
from collections import Counter
import hashlib
import json

import identified_events
import identified_queue


SCENARIOS = (
    # name, feed delay, order delay, response delay, decision time, cancel time
    ("before-u", 0, 0, 0, 101, None),
    ("at-u", 0, 9, 0, 101, None),
    ("no-feed", 11, 0, 0, 101, None),
    ("arrival-pending", 0, 10, 0, 101, None),
    ("ack-pending", 0, 0, 11, 101, None),
    ("cancel", 0, 0, 0, 101, 102),
    ("cancel-ack-pending", 0, 0, 5, 101, 107),
    ("cancel-arrival-pending", 0, 2, 0, 101, 109),
    ("delayed-seed", 10, 0, 0, 110, None),
)
FINAL_FIELDS = (
    "external_level_shares", "ahead_shares", "exchange_state", "exchange_remaining",
    "accepted_quantity", "cancelled_quantity", "local_state", "local_request_quantity",
    "local_confirmed_remaining", "submitted", "cancel_requested",
    "exchange_account", "local_account",
)
AUTHENTICATION_FIELDS = (
    "raw_input_identity_verified", "status_admission_verified", "source_coverage_authenticated",
)
LIMITATIONS = [
    "Fictional orders and clocks; no historical market data or private fixtures are required.",
    "The generated byte digest is not exchange authenticity, session admission or a raw-file verification.",
    "One passive one-share buy and one atomic U; pending events do not extend the inclusive source horizon.",
    "Zero fills, cash changes and fees in this no-execution example; no actual priority, market reaction or empirical calibration is established.",
]


def fictional_ledger():
    """Build a hand-seeded ledger and encode its one atomic replacement."""
    orders, frames = [], []
    for reference, side, shares, price in (
            (10, "B", 10, 100), (20, "B", 40, 100),
            (30, "B", 30, 100), (50, "S", 20, 101)):
        orders.append(dict(reference=reference, side=side, shares=shares, price4=price,
                           attribution=dict(kind="absent_in_wire", mpid=None)))
        body = (b"A" + (1).to_bytes(2, "big") + bytes(2) + (100).to_bytes(6, "big") +
                reference.to_bytes(8, "big") + side.encode("ascii") + shares.to_bytes(4, "big") +
                b"DEMO    " + price.to_bytes(4, "big"))
        frames.append(len(body).to_bytes(2, "big") + body)
    body = (b"U" + (1).to_bytes(2, "big") + bytes(2) + (110).to_bytes(6, "big") +
            (20).to_bytes(8, "big") + (40).to_bytes(8, "big") +
            (40).to_bytes(4, "big") + (100).to_bytes(4, "big"))
    frames.append(len(body).to_bytes(2, "big") + body)
    wire = b"".join(frames)
    identity = dict(input_bytes=len(wire), input_sha256=hashlib.sha256(wire).hexdigest(),
                    evidence_sha256=None, verification="unverified_by_module")
    pre = dict(sequence=4, frame_offset=114, frame_end_offset=152,
               timestamp_ns=100, body_bytes=36, type="A")
    post = dict(sequence=5, frame_offset=152, frame_end_offset=189,
                timestamp_ns=110, body_bytes=35, type="U")
    seed = dict(source=pre, effective_ns=100, boundary="post_source_message",
                derived=True, orders=orders)
    ledger = identified_events.build_ledger("DEMO", 1, identity, seed,
                                             [(post, frames[-1])], [post])
    return ledger, post


def summarise(name, result):
    """Project the model's actual final state; do not calculate queue outcomes."""
    final = result["final"]
    row = {key: final[key] for key in FINAL_FIELDS}
    row.update(scenario=name, config=result["config"], trace_rows=len(result["trace"]),
               observed_inventory=dict(event_index=final["observed_event_index"],
                                       origin_ns=final["observed_origin_ns"],
                                       delivery_ns=final["observed_delivery_ns"],
                                       sha256=final["observed_inventory_sha256"]),
               pending_by_kind=dict(Counter(event["event"] for event in result["pending"])),
               next_pending_ns=min((event["time_ns"] for event in result["pending"]), default=None))
    return row


class Once(argparse.Action):
    def __call__(self, parser, namespace, values, option_string=None):
        if getattr(namespace, "_scenario_seen", False):
            parser.error("--scenario may be supplied only once")
        namespace._scenario_seen = True
        setattr(namespace, self.dest, values)


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__, allow_abbrev=False)
    parser.add_argument("--scenario", choices=["all"] + [row[0] for row in SCENARIOS],
                        default="all", action=Once, help="select one example (default: all)")
    selected = parser.parse_args(argv).scenario
    ledger, post = fictional_ledger()
    results, first = [], None
    for name, feed, order, response, decision, cancel in SCENARIOS:
        if selected != "all" and selected != name:
            continue
        config = dict(quantity=1, decision_ns=decision, cancel_ns=cancel, horizon_ns=110,
                      feed_delay_ns=feed, order_delay_ns=order, response_delay_ns=response)
        actual = identified_queue.simulate_one_u(ledger, config, [post])
        if first is None:
            first = actual
        results.append(summarise(name, actual))
    report = dict(schema_version=1, model="one_u_queue_demo_v1", synthetic=True,
                  historical_data_used=False, source_generated_in_memory=True,
                  synthetic_source_identity=ledger["source_identity"], symbol="DEMO", locate=1,
                  seed_time_ns=100, horizon_ns=110,
                  phase_order=["source", "feed", "strategy", "arrival", "response"],
                  inventory_sha256={name: identified_queue.inventory_sha256(state["orders"])
                                    for name, state in zip(("pre", "post"), first["historical_snapshots"])},
                  authentication={key: first[key] for key in AUTHENTICATION_FIELDS},
                  scenario_count=len(results), results=results, limitations=LIMITATIONS)
    sys.stdout.write(json.dumps(report, indent=2, sort_keys=True, ensure_ascii=True,
                                allow_nan=False) + "\n")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
